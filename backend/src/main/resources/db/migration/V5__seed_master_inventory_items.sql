-- Seed initial active FEFO batch for each item
INSERT INTO inventory_batches (
    inventory_item_id, batch_number, quantity_received, quantity_remaining, quantity_reserved,
    received_date, expiry_date, unit_cost, is_active, status, created_at
)
SELECT
    i.id,
    'BATCH-' || i.sku || '-01',
    i.current_stock,
    i.current_stock,
    0.0,
    CURRENT_DATE - INTERVAL '10' DAY,
    CURRENT_DATE + INTERVAL '730' DAY,
    i.avg_unit_cost,
    true,
    'AVAILABLE',
    CURRENT_TIMESTAMP
FROM inventory_items i
WHERE NOT EXISTS (
    SELECT 1 FROM inventory_batches b WHERE b.inventory_item_id = i.id
);
