export const normalizeRole = (role) => ROLE_ALIASES[role] || role;

export const hasPermission = (role, permission) => {
  if (!role || !permission) return false;
  const perms = ROLE_PERMISSIONS[role] || ROLE_PERMISSIONS[normalizeRole(role)] || [];
  return perms.includes(permission);
};

export const hasAnyPermission = (role, permissions) => {
  if (!role || !permissions?.length) return false;
  return permissions.some((p) => hasPermission(role, p));
};

export const hasAllPermissions = (role, permissions) => {
  if (!role || !permissions?.length) return false;
  return permissions.every((p) => hasPermission(role, p));
};

export const getRolePermissions = (role) => ROLE_PERMISSIONS[role] || ROLE_PERMISSIONS[normalizeRole(role)] || [];

